-- PakPulse 001: initial schema
-- Applied to Supabase on 2026-10-20 (SQL Editor, "Run and enable RLS").
-- Creates the pakpulse schema and its 16 tables. See docs/DATABASE.md for what each table holds.

begin;

create schema if not exists pakpulse;
create extension if not exists vector with schema extensions;

-- A. Topic setup
create table pakpulse.topics (
  id          bigint generated by default as identity primary key,
  name        text not null,
  description text,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table pakpulse.topic_keywords (
  id         bigint generated by default as identity primary key,
  topic_id   bigint not null references pakpulse.topics(id) on delete cascade,
  keyword    text not null,
  language   text not null check (language in ('en','ur','roman_ur')),
  created_at timestamptz not null default now(),
  unique (topic_id, keyword)
);

create table pakpulse.topic_accounts (
  id         bigint generated by default as identity primary key,
  topic_id   bigint not null references pakpulse.topics(id) on delete cascade,
  platform   text not null check (platform in ('x','instagram','threads')),
  handle     text not null,
  category   text check (category in ('official','journalist','analyst','commentator','news')),
  created_at timestamptz not null default now(),
  unique (topic_id, platform, handle)
);

-- B. Collection (raw data, untouched)
create table pakpulse.collection_rounds (
  id           bigint generated by default as identity primary key,
  topic_id     bigint not null references pakpulse.topics(id) on delete cascade,
  round_number int not null check (round_number > 0),
  label        text not null,
  status       text not null default 'planned' check (status in ('planned','running','completed','failed')),
  started_at   timestamptz,
  finished_at  timestamptz,
  notes        text,
  created_at   timestamptz not null default now(),
  unique (topic_id, round_number)
);

create table pakpulse.raw_posts (
  id                  bigint generated by default as identity primary key,
  collection_round_id bigint not null references pakpulse.collection_rounds(id) on delete cascade,
  source              text not null check (source in ('file_import','apify','twitterapi_io','threads_api','custom')),
  platform            text not null check (platform in ('x','instagram','threads')),
  platform_post_id    text not null,
  payload             jsonb not null,
  fetched_at          timestamptz not null default now(),
  unique (collection_round_id, platform, platform_post_id)
);

-- C. Cleaned posts
create table pakpulse.posts (
  id                      bigint generated by default as identity primary key,
  topic_id                bigint not null references pakpulse.topics(id) on delete cascade,
  platform                text not null check (platform in ('x','instagram','threads')),
  platform_post_id        text not null,
  url                     text,
  posted_at               timestamptz,
  text                    text not null default '',
  text_normalised         text,
  text_hash               text,
  language                text check (language in ('en','ur','roman_ur','mixed','other')),
  author_platform_id      text,
  author_handle           text,
  author_display_name     text,
  author_followers        bigint,
  parent_platform_post_id text,
  parent_text             text,
  is_reply                boolean not null default false,
  is_quote                boolean not null default false,
  hashtags                text[] not null default '{}',
  mentions                text[] not null default '{}',
  media_urls              text[] not null default '{}',
  likes                   bigint not null default 0,
  reposts                 bigint not null default 0,
  replies                 bigint not null default 0,
  quotes                  bigint not null default 0,
  views                   bigint,
  status                  text not null default 'new' check (status in ('new','clean','dropped')),
  drop_reason             text,
  first_seen_round_id     bigint references pakpulse.collection_rounds(id) on delete set null,
  last_seen_round_id      bigint references pakpulse.collection_rounds(id) on delete set null,
  latest_raw_post_id      bigint references pakpulse.raw_posts(id) on delete set null,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  unique (topic_id, platform, platform_post_id)
);
create index posts_topic_status_idx on pakpulse.posts (topic_id, status);
create index posts_text_hash_idx    on pakpulse.posts (text_hash);

create table pakpulse.post_metrics (
  post_id             bigint not null references pakpulse.posts(id) on delete cascade,
  collection_round_id bigint not null references pakpulse.collection_rounds(id) on delete cascade,
  likes               bigint not null default 0,
  reposts             bigint not null default 0,
  replies             bigint not null default 0,
  quotes              bigint not null default 0,
  views               bigint,
  recorded_at         timestamptz not null default now(),
  primary key (post_id, collection_round_id)
);

-- F. Operations (created early because analysis tables refer to it)
create table pakpulse.pipeline_runs (
  id                  bigint generated by default as identity primary key,
  topic_id            bigint references pakpulse.topics(id) on delete cascade,
  collection_round_id bigint references pakpulse.collection_rounds(id) on delete set null,
  stage               text not null check (stage in ('collect','normalise','clean','language_tag','label','embed','narratives','brief')),
  status              text not null default 'running' check (status in ('running','succeeded','failed','stopped_budget')),
  is_test_run         boolean not null default false,
  items_in            int,
  items_out           int,
  error               text,
  started_at          timestamptz not null default now(),
  finished_at         timestamptz
);

create table pakpulse.spend_entries (
  id              bigint generated by default as identity primary key,
  pipeline_run_id bigint references pakpulse.pipeline_runs(id) on delete set null,
  service         text not null check (service in ('apify','twitterapi_io','llm_label','llm_brief','embeddings')),
  units           int not null,
  unit_type       text not null,
  cost_usd        numeric(10,4) not null,
  usd_to_pkr_rate numeric(8,2) not null,
  created_at      timestamptz not null default now()
);

-- D. Analysis
create table pakpulse.post_labels (
  id                   bigint generated by default as identity primary key,
  post_id              bigint not null references pakpulse.posts(id) on delete cascade,
  pipeline_run_id      bigint references pakpulse.pipeline_runs(id) on delete set null,
  sentiment            text check (sentiment in ('positive','negative','neutral','mixed')),
  sentiment_confidence real check (sentiment_confidence between 0 and 1),
  emotion              text check (emotion in ('anger','joy','fear','sadness','pride','disgust','surprise','none')),
  emotion_confidence   real check (emotion_confidence between 0 and 1),
  stance               text check (stance in ('supportive','critical','neutral','off_topic')),
  stance_confidence    real check (stance_confidence between 0 and 1),
  sarcasm_probability  real check (sarcasm_probability between 0 and 1),
  sarcasm_confidence   real check (sarcasm_confidence between 0 and 1),
  language_detected    text check (language_detected in ('en','ur','roman_ur','mixed','other')),
  rationale            text,
  source               text not null check (source in ('llm','human')),
  model                text,
  prompt_version       text,
  is_current           boolean not null default true,
  created_at           timestamptz not null default now()
);
create unique index post_labels_one_current_idx on pakpulse.post_labels (post_id) where is_current;
create index post_labels_post_idx on pakpulse.post_labels (post_id);

create table pakpulse.review_items (
  id          bigint generated by default as identity primary key,
  post_id     bigint not null references pakpulse.posts(id) on delete cascade,
  label_id    bigint not null references pakpulse.post_labels(id) on delete cascade,
  reason      text not null,
  status      text not null default 'pending' check (status in ('pending','resolved','skipped')),
  created_at  timestamptz not null default now(),
  resolved_at timestamptz
);
create index review_items_status_idx on pakpulse.review_items (status);

create table pakpulse.post_embeddings (
  post_id    bigint primary key references pakpulse.posts(id) on delete cascade,
  model      text not null,
  embedding  extensions.vector not null,
  created_at timestamptz not null default now()
);

-- E. Insights
create table pakpulse.narratives (
  id                   bigint generated by default as identity primary key,
  topic_id             bigint not null references pakpulse.topics(id) on delete cascade,
  pipeline_run_id      bigint references pakpulse.pipeline_runs(id) on delete set null,
  title                text not null,
  summary              text,
  post_count           int not null default 0,
  share_latest_round   real,
  share_previous_round real,
  growth_score         real,
  is_emerging          boolean not null default false,
  created_at           timestamptz not null default now()
);

create table pakpulse.narrative_posts (
  narrative_id      bigint not null references pakpulse.narratives(id) on delete cascade,
  post_id           bigint not null references pakpulse.posts(id) on delete cascade,
  similarity        real,
  is_representative boolean not null default false,
  primary key (narrative_id, post_id)
);
create index narrative_posts_post_idx on pakpulse.narrative_posts (post_id);

create table pakpulse.briefs (
  id               bigint generated by default as identity primary key,
  topic_id         bigint not null references pakpulse.topics(id) on delete cascade,
  pipeline_run_id  bigint references pakpulse.pipeline_runs(id) on delete set null,
  brief_date       date not null,
  model            text,
  content_markdown text not null,
  created_at       timestamptz not null default now()
);

create table pakpulse.brief_citations (
  brief_id bigint not null references pakpulse.briefs(id) on delete cascade,
  post_id  bigint not null references pakpulse.posts(id) on delete cascade,
  primary key (brief_id, post_id)
);

-- Security: only the backend's own login can use these tables
do $$
declare t record;
begin
  for t in select tablename from pg_tables where schemaname = 'pakpulse' loop
    execute format('alter table pakpulse.%I enable row level security', t.tablename);
  end loop;
end $$;
revoke all on schema pakpulse from anon, authenticated;
revoke all on all tables in schema pakpulse from anon, authenticated;
alter default privileges in schema pakpulse revoke all on tables from anon, authenticated;

commit;
